document.getElementById("btnSearch").addEventListener("click", function () {
  const fromDate = document.getElementById("fromDate").value;
  const fromTime = document.getElementById("fromTime").value;
  const toDate = document.getElementById("toDate").value;
  const toTime = document.getElementById("toTime").value;
  const selectedCar = document.getElementById("carSelect").value;

  console.log("from date: ", fromDate);
  console.log("to date: ", toDate);
  console.log("from time: ", fromTime);
  console.log("to time: ", toTime);

  if (!selectedCar) {
    alert("Vui lòng chọn biển số xe");
    return;
  }

  // Lấy dữ liệu của xe
  const data = allRouteData[selectedCar];
  if (!data || data.length === 0) {
    alert("Không có dữ liệu cho xe này");
    return;
  }

  // ====== Lọc theo thời gian ======
  // Ghép ngày + giờ => Date object
  // (ở demo này, ta chỉ dùng giờ vì mock không có ngày thực)
  const fromDateTime = new Date(`2025-12-22 ${fromTime || "00:00"}`);
  const toDateTime = new Date(`2025-12-22 ${toTime || "23:59"}`);

  const filtered = data.filter((d) => {
    const itemTime = new Date(`2025-12-22 ${d.time}`);
    return itemTime >= fromDateTime && itemTime <= toDateTime;
  });
  console.log(filtered);

  if (filtered.length === 0) {
    alert("Không có dữ liệu trong khoảng thời gian đã chọn");
    return;
  }

  resetMap(); // Xoá dữ liệu cũ
  drawRoute(filtered); // Vẽ lại tuyến đường
});
