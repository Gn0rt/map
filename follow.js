var map = L.map("map").setView([20.99, 105.73], 13);

L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", {
  maxZoom: 19,
  attribution:
    '&copy; <a href="http://www.openstreetmap.org/copyright">OpenStreetMap</a>',
}).addTo(map);

let polylineNoCustomer = L.polyline([], { color: "gray", weight: 4 }).addTo(
  map
);
let polylineHasCustomer = L.polyline([], { color: "green", weight: 4 }).addTo(
  map
);
let marker = null;
let tbody = document.querySelector("#log-table tbody");

// Biến tổng
let totalHasCustomer = 0;
let totalNoCustomer = 0;
let prevPoint = null; // Dùng để tính km giữa các điểm

// ======================== HÀM TIỆN ÍCH ========================
function resetMap() {
  map.eachLayer((layer) => {
    if (layer instanceof L.Polyline || layer instanceof L.Marker) {
      map.removeLayer(layer);
    }
  });

  // Thêm lại tile
  L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", {
    maxZoom: 19,
  }).addTo(map);
  // Reset bảng và tổng
  tbody.innerHTML = "";
  document.querySelector(".hasCustomer").textContent = "0 km";
  document.querySelector(".noCustomer").textContent = "0 km";
  document.querySelector(".total").textContent = "0 km";

  totalHasCustomer = 0;
  totalNoCustomer = 0;
  prevPoint = null; // reset lại để tính lại từ đầu

  // Reset polyline
  polylineNoCustomer = L.polyline([], { color: "gray", weight: 4 }).addTo(map);
  polylineHasCustomer = L.polyline([], { color: "green", weight: 4 }).addTo(
    map
  );
  marker = null;
}
function updateTotals(currentPoint) {
  let kmSegment = 0;

  // Tính quãng đường thực tế giữa hai điểm
  if (prevPoint) {
    kmSegment = currentPoint.km - prevPoint.km;
    if (kmSegment < 0) kmSegment = 0; // tránh lỗi nếu data sai thứ tự
  } else {
    kmSegment = 0; // điểm đầu tiên không tính quãng đường
  }

  // Cộng tổng theo trạng thái
  if (currentPoint.hasCustomer) {
    totalHasCustomer += kmSegment;
  } else {
    totalNoCustomer += kmSegment;
  }

  const total = totalHasCustomer + totalNoCustomer;

  document.querySelector(".hasCustomer").textContent =
    totalHasCustomer.toFixed(2) + " km";
  document.querySelector(".noCustomer").textContent =
    totalNoCustomer.toFixed(2) + " km";
  document.querySelector(".total").textContent = total.toFixed(2) + " km";

  // Lưu lại để tính cho lần kế tiếp
  prevPoint = currentPoint;
}

function addRow(data) {
  const row = document.createElement("tr");
  if (data.hasCustomer) row.classList.add("has-customer");

  row.dataset.lat = data.lat;
  row.dataset.lng = data.lng;
  console.log(row.dataset.lat);
  console.log(row.dataset.lng);

  row.innerHTML = `
    <td>${data.time}</td>
    <td>${data.speed} km/h</td>
    <td>${data.km.toFixed(1)} km</td>
    <td>${data.hasCustomer ? "Có khách" : "Trống"}</td>
  `;
  // Khi click vào row => pan đến toạ độ tương ứng
  row.addEventListener("click", function () {
    const lat = parseFloat(this.dataset.lat);
    const lng = parseFloat(this.dataset.lng);
    const latlng = [lat, lng];

    // Di chuyển bản đồ đến vị trí đó (không di chuyển marker)
    map.panTo(latlng, { animate: true, duration: 1.0 });
  });
  tbody.appendChild(row);
  tbody.scrollTop = tbody.scrollHeight;
}
// ======================== VẼ LỘ TRÌNH ========================
function drawRoute(data) {
  let index = 0;

  function step() {
    if (index >= data.length) return;

    const point = data[index];
    const latlng = [point.lat, point.lng];

    if (!marker) {
      marker = L.marker(latlng).addTo(map).bindPopup(`${point.bx}`).openPopup();
    } else {
      marker.setLatLng(latlng);
    }
    map.panTo(latlng);

    if (point.hasCustomer) polylineHasCustomer.addLatLng(latlng);
    else polylineNoCustomer.addLatLng(latlng);

    addRow(point);
    updateTotals(point);

    index++;
    if (index < data.length) setTimeout(step, 1500);
  }

  step();
}
